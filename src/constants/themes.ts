export const DEFAULT_THEME = COLOR_THEMES[0];

export function getThemeById(id?: string): ColorTheme {
  if (!id) return DEFAULT_THEME;
  const match = COLOR_THEMES.find((t) => t.id === id);
  if (match) return match;

  // Backward compatibility: map legacy template IDs to corresponding theme
  const legacyMap: Record<string, string> = {
    tpl_nordic_clean: "theme_nordic_pine",
    tpl_tech_monolith: "theme_obsidian_slate",
    tpl_editorial_minimal: "theme_monochrome_ink",
    tpl_warm_organic: "theme_warm_terracotta",
    tpl_classic_boutique: "theme_amber_heritage",
    tpl_bold_grid: "theme_crimson_impact",
    tpl_vibrant_modern: "theme_electric_indigo",
    tpl_luxury_haute: "theme_haute_champagne",
  };

  const mappedId = legacyMap[id];
  if (mappedId) {
    const legacyMatch = COLOR_THEMES.find((t) => t.id === mappedId);
    if (legacyMatch) return legacyMatch;
  }

  return DEFAULT_THEME;
}

export function resolveColorTokens(id?: string): ColorThemeTokens {
  return getThemeById(id).tokens;
}
